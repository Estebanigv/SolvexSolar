import assert from 'node:assert/strict';
import {newQuote,calculate,initialProducts,initialSettings,type SavedQuote} from '../lib/quote';
import {documentTitle,isIssued,issuanceProblems,issuanceWarnings} from '../lib/quote-issuance';
const input={...newQuote(),customer:{...newQuote().customer,name:'Cliente prueba',email:'prueba@example.com'}};
const settings={...initialSettings,taxMode:'included' as const};
const draft:SavedQuote={id:'draft',folio:'BORRADOR-SVX',date:'2026-10-02T12:00:00Z',input,settings,calculation:calculate(input,initialProducts,settings)};
assert.deepEqual(issuanceProblems(draft),[],'Una propuesta preliminar completa puede emitirse, manteniendo sus condiciones técnicas');
assert.equal(documentTitle(draft),'PRECOTIZACIÓN');
const issued={...draft,id:'persisted',folio:'SVX-2026-000001',issuedAt:'2026-10-03T00:15:00Z'};
assert.equal(isIssued(issued),true);
assert.equal(documentTitle(issued),'COTIZACIÓN');
assert.equal(issued.calculation.official,false,'Emitir no inventa una aprobación técnica');
assert.equal(isIssued({...issued,folio:'BORRADOR-SVX'}),false);
assert.equal(isIssued({...issued,issuedAt:undefined}),false);
assert.deepEqual(issuanceProblems({...draft,calculation:{...draft.calculation,complete:false}}),[]);
assert.deepEqual(issuanceProblems({...draft,settings:initialSettings}),[]);
assert.ok(issuanceProblems({...draft,input:{...input,customer:{...input.customer,name:''}}}).length);
assert.deepEqual(issuanceProblems({...draft,input:{...input,proposalType:'final'}}),[],'Se puede emitir con advertencias sin aprobar técnicamente');
assert.deepEqual(issuanceProblems({...draft,input:{...input,proposalType:'final'},calculation:{...draft.calculation,official:true}}),[]);
console.log('Emisión: título, folio, validaciones y aprobación técnica independiente: OK');

const noContact={...draft,input:{...input,customer:{...input.customer,email:'',phone:''}}};
assert.deepEqual(issuanceProblems(noContact),[]);
assert.ok(issuanceWarnings(noContact).some(w=>w.includes('contacto')));
const partial={...noContact,settings:initialSettings,input:{...noContact.input,proposalType:'final' as const},calculation:{...noContact.calculation,complete:false,tax:null}};
const warnings=issuanceWarnings(partial);
assert.ok(warnings.some(w=>w.includes('importe es parcial')));
assert.ok(warnings.some(w=>w.includes('IVA')));
assert.ok(warnings.some(w=>w.includes('aprobación técnica')));
assert.equal(new Set(warnings).size,warnings.length);
for(const total of [0,-1,NaN,Infinity])assert.ok(issuanceProblems({...draft,calculation:{...draft.calculation,total}}).length);
const withWarnings={...issued,issuanceWarnings:warnings};
assert.equal(documentTitle(withWarnings),'COTIZACIÓN CON PENDIENTES');

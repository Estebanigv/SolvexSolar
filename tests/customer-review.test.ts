import assert from 'node:assert/strict';
import {customerReviewKey,needsCustomerReview} from '../lib/customer-review';
import {newQuote} from '../lib/quote';
const customer={...newQuote().customer,name:'Cliente de prueba',address:'Calle 123',commune:'Chillán',region:'Ñuble'};
const documents=[{id:'file-1',rotation:0}];
const accepted=customerReviewKey(customer,documents,1);
assert.equal(needsCustomerReview(accepted,null),true);
assert.equal(needsCustomerReview(accepted,accepted),false);
assert.equal(needsCustomerReview(customerReviewKey(customer,[],null),null),false,'El ingreso manual no requiere revisión de boleta');
for(const key of ['name','email','phone','address','commune','region','bill'] as const){
  const changed={...customer,[key]:key==='bill'?10000:'Corrección'};
  assert.equal(needsCustomerReview(customerReviewKey(changed,documents,1),accepted),true,`Volver a revisar ${key}`);
}
assert.equal(needsCustomerReview(customerReviewKey(customer,[{id:'file-2'}],1),accepted),true);
assert.equal(needsCustomerReview(customerReviewKey(customer,[{id:'file-1',rotation:90}],1),accepted),true);
assert.equal(needsCustomerReview(customerReviewKey(customer,documents,2),accepted),true);
assert.equal(needsCustomerReview(customerReviewKey(customer,documents,null),accepted),true,'Relectura o cancelación invalida revisión');
console.log('Cliente leído: revisión, correcciones, documentos nuevos y relectura: OK');

// Only the editable form displays customer values after a successful read.
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {CustomerBillReview} from '../app/customer-bill-review';
import {ClientSelection} from '../app/client-selection';
import {BillReview} from '../app/bill-review';
import {autoFillBill,extractBill} from '../lib/bill-extraction';
const extraction=extractBill(['Titular: Persona Ficticia\nDirección de suministro: Calle Ejemplo 100, Temuco\nTotal a pagar $ 80.000\nElectricidad consumida (321 kWh)\nDías facturados: 30']);
const loaded=autoFillBill(newQuote(),extraction);
const quote={...newQuote(),...loaded.patch};
const noAction=()=>{};
const resultMarkup=(result=loaded.result,input=quote)=>renderToStaticMarkup(createElement(BillReview,{result,quote:input,disabled:false,onApply:noAction}));
const markup=resultMarkup();
assert.ok(!markup.includes('Resumen de datos detectados'));
assert.ok(!markup.includes('bill-read-overview'));
assert.ok(!markup.includes('Dato detectado:'));
assert.ok(!markup.includes('Revisar diferencias'));
const confirmed=renderToStaticMarkup(createElement(CustomerBillReview,{customer:quote.customer,checked:true,busy:false,onChange:noAction,onEdit:noAction}));
assert.ok(!confirmed.includes(quote.customer.name));
assert.ok(!confirmed.includes('<dl'));
assert.ok(confirmed.includes('customer-bill-confirm'));
const waiting=renderToStaticMarkup(createElement(CustomerBillReview,{customer:quote.customer,checked:false,busy:true,progress:'Leyendo página 1',onChange:noAction,onEdit:noAction}));
assert.ok(waiting.includes('Leyendo página 1'));
assert.ok(waiting.includes('customer-read-skeleton'));
assert.ok(waiting.includes('disabled=""'));
const selection=renderToStaticMarkup(createElement(ClientSelection,{customer:quote.customer,clientId:null,clients:[],onSelect:noAction}));
assert.ok(!selection.includes(quote.customer.name));
assert.ok(!selection.includes(quote.customer.address));
assert.ok(selection.includes('Buscar un cliente registrado'));
const conflict=resultMarkup(loaded.result,{...quote,customer:{...quote.customer,name:'Dato manual'}});
assert.ok(conflict.includes('Revisar diferencias (1)'));
assert.ok(conflict.includes('Dato detectado: Nombre del cliente'));
assert.ok(!conflict.includes('Dato detectado: Dirección'));
const formatted=resultMarkup({...loaded.result,values:{...loaded.result.values,bill:'80.000'}});
assert.ok(!formatted.includes('Revisar diferencias'));
const location=resultMarkup(loaded.result,{...quote,customer:{...quote.customer,region:'Ñuble',commune:'Chillán'}});
assert.ok(location.includes('Ubicación detectada en la boleta'));
assert.ok(location.includes('Aplicar región'));
const missing=resultMarkup({...loaded.result,values:{...loaded.result.values,consumptionKwh:undefined},warnings:['Falta el consumo en kWh.']});
assert.ok(missing.includes('Falta el consumo en kWh.'));
console.log('Boleta sin datos duplicados: formulario único, revisión, carga, diferencias y alertas conservadas: OK');

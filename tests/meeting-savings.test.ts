import assert from 'node:assert/strict';
import {automaticSavings,newProjection,resolvedProjection,publishedProjection,projectionContext} from '../lib/projection';
import {calculate,newQuote,initialProducts,initialSettings,mergeQuotePatch,quoteSchema,type SavedQuote} from '../lib/quote';
import {newEnergyInput,solarGenerationContext} from '../lib/energy';
import {combineBillCodes} from '../lib/bill-code-extraction';
import {extractBill} from '../lib/bill-extraction';
const input={...newQuote(),customer:{...newQuote().customer,bill:200000},energy:{...newEnergyInput(),consumptionKwh:1000,billingDays:30}};
const settings={...initialSettings,taxMode:'included' as const};
const q:SavedQuote={id:'test',folio:'SVX-2026-000040',date:'2026-10-13',input,settings,calculation:{...calculate(input,initialProducts,settings),kwp:3.51}};
const p={...newProjection(),generationMethod:'hsp' as const,peakSunHours:4.1,referenceDays:30,referenceLossPercent:0,energyRate:200,selfConsumptionPercent:100};
assert.equal(automaticSavings(q,p).result?.monthlySavings,86346);
assert.equal(automaticSavings({...q,calculation:{...q.calculation,kwp:7.02}},p).result?.monthlySavings,172692);
const lowDemand={...q,input:{...input,energy:{...input.energy,consumptionKwh:100}}};
assert.equal(automaticSavings(lowDemand,p).result?.monthlySavings,20000);
assert.equal(automaticSavings(lowDemand,{...p,selfConsumptionPercent:0}).result?.monthlySavings,0);
assert.equal(automaticSavings(q,{...p,referenceLossPercent:10}).result?.monthlySavings,77711);
assert.equal(automaticSavings(q,{...p,peakSunHours:0}).result,null);
const inferred=automaticSavings({...q,input:{...input,energy:undefined}},{...p,consumptionMethod:'amount' as const,nonEnergyCharges:10000}).result!;
assert.equal(inferred.monthlyConsumption,950);assert.equal(inferred.estimatedConsumption,true);
assert.equal(automaticSavings({...q,input:{...input,energy:undefined}},{...p,consumptionMethod:'amount',energyRate:null}).result,null);
const offgrid={...q,input:{...input,system:'OFF GRID' as const}};
assert.equal(automaticSavings(offgrid,{...p,consumptionMethod:'amount'}).result,null);
assert.equal(automaticSavings(offgrid,{...p,exportRate:500}).result?.exportCredit,0);
const seasonal={...q,input:{...input,energy:{...input.energy,consumptionKwh:300,solarGeneration:{annualKwh:6000,context:solarGenerationContext(input.energy,q.calculation.kwp),retrievedAt:'2026-10-13T12:00:00Z',source:'Synthetic seasonal case',monthly:Array.from({length:12},(_,i)=>({month:i+1,kwh:i<6?0:1000}))}}}};
const seasonalResult=automaticSavings(seasonal,{...newProjection(),generationMethod:'pvgis',selfConsumptionPercent:100,energyRate:200}).result!;
assert.ok(seasonalResult.monthlySavings<61000);assert.equal(seasonalResult.monthly?.length,12);
for(const row of seasonalResult.monthly!)assert.ok(Math.abs(row.generation-row.selfConsumed-row.surplus)<1e-9);
const draft:SavedQuote={...q,input:{...q.input,projection:p}};
const resolved=resolvedProjection(draft);draft.input.projection={...resolved,reviewedFor:projectionContext(draft,resolved)};
assert.ok(publishedProjection(draft));
assert.equal(publishedProjection({...draft,calculation:{...draft.calculation,kwp:4}}),null);
assert.ok(quoteSchema.safeParse(draft.input).success);
const fixed={...input,finalTotalOverride:13000000,projection:p};
assert.equal(mergeQuotePatch(fixed,{quantities:{...fixed.quantities,'0-10':12}}).finalTotalOverride,null);
assert.equal(mergeQuotePatch(fixed,{notes:'only text'}).finalTotalOverride,13000000);
assert.equal(newQuote().projection,undefined);assert.equal(newQuote().finalTotalOverride,null);
const code=(text:string)=>({format:'QRCode',text});
assert.equal(combineBillCodes(extractBill([]),[code('https://boletas.cge.cl/pago?valor=999')]).values.distributor,'CGE');
assert.equal(combineBillCodes(extractBill([]),[code('https://cge.cl.attacker.test/boleta')]).values.distributor,undefined);
assert.equal(combineBillCodes(extractBill([]),[code('https://enel.cl/pago?kwh=999')]).values.consumptionKwh,undefined);
assert.equal(combineBillCodes(extractBill(['CGE']),[code('https://enel.cl/boleta')]).values.distributor,undefined);
const structured=combineBillCodes(extractBill([]),[code('Consumo del período: 400 kWh\nDías facturados: 30\nTotal a pagar: $80.000')]);
assert.equal(structured.values.consumptionKwh,'400');assert.equal(structured.values.bill,'80000');
console.log('Minuta: HSP, límites de consumo, estacionalidad, persistencia, invalidación, total y QR: OK');


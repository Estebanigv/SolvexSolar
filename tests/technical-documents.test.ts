import assert from 'node:assert/strict';
import {productSchema,settingsSchema,initialSettings,type Product} from '../lib/quote';
import {technicalLibrarySchema,technicalDocumentSchema,productDocuments} from '../lib/technical-documents';
const panel:Product={id:'test',system:'ON GRID',category:'PANEL',name:'Panel',price:123456,watts:585,unit:'unidad',source:'test'};
const doc={id:'a',name:'Ficha.pdf',model:'Modelo 585',category:'PANEL',watts:[580,585,590],url:'https://drive.google.com/file/d/example/view'};
const library={folderUrl:'https://drive.google.com/drive/folders/example',documents:[doc,{...doc,id:'b',model:'Modelo 620',watts:[620]}]};
assert.ok(productSchema.safeParse(panel).success);
assert.ok(settingsSchema.safeParse(initialSettings).success);
assert.deepEqual(settingsSchema.parse({...initialSettings,technicalLibrary:library}).technicalLibrary,library);
assert.deepEqual(productDocuments(panel,library).candidates.map(d=>d.id),['a']);
assert.equal(productDocuments(panel,library).linked,undefined,'Potencia no acredita modelo');
assert.equal(productDocuments(productSchema.parse({...panel,technicalDocumentId:'a'}),library).linked?.id,'a');
assert.equal(productDocuments({...panel,technicalDocumentId:'b'},library).linked,undefined);
assert.deepEqual(productDocuments({...panel,watts:620},library).candidates.map(d=>d.id),['b']);
assert.equal(productDocuments({...panel,category:'INVERSOR'},library).candidates.length,0);
assert.equal(productDocuments(panel).candidates.length,0);
for(const url of ['bad','javascript:alert(1)','http://drive.google.com/a','https://evil.example/a','https://drive.google.com.evil.example/a','https://user@drive.google.com/a'])assert.equal(technicalDocumentSchema.safeParse({...doc,url}).success,false,url);
assert.equal(technicalLibrarySchema.safeParse({...library,documents:[doc,doc]}).success,false);
assert.equal(panel.price,123456);
console.log('Technical documents: OK');
